def main() -> None:
    args = parse_args()

    source_root = (
        args.source.resolve()
    )

    destination_root = (
        args.destination.resolve()
    )

    if not source_root.is_dir():
        raise SystemExit(
            "Source directory does not exist: "
            f"{source_root}"
        )

    if (
        source_root
        == destination_root
    ):
        raise SystemExit(
            "Source and destination must "
            "be different directories."
        )

    source_size = directory_size(
        source_root
    )

    if destination_root.exists():
        shutil.rmtree(
            destination_root
        )

    destination_root.mkdir(
        parents=True,
        exist_ok=True,
    )

    copied = 0
    missing_required: list[Path] = []

    for relative_path in required_copy_assets():
        if copy_asset(
            source_root,
            destination_root,
            relative_path,
        ):
            copied += 1
        else:
            missing_required.append(
                relative_path
            )

    for relative_path in OPTIONAL_FIGURES:
        if copy_asset(
            source_root,
            destination_root,
            relative_path,
        ):
            copied += 1
        else:
            missing_required.append(
                relative_path
            )

    generated, missing_generated_inputs = generate_latex_tables(
        source_root,
        destination_root,
    )
    figures, missing_plot_inputs = generate_runtime_accuracy_tradeoff(
        source_root,
        destination_root,
    )

    # De-duplicate paths while preserving order.
    missing = list(
        dict.fromkeys(
            [
                *missing_required,
                *missing_generated_inputs,
                *missing_plot_inputs,
            ]
        )
    )

    destination_size = directory_size(
        destination_root
    )

    print()
    print(
        "Overleaf thesis-results export complete"
    )
    print(
        "========================================"
    )
    print(
        f"Source:      {source_root}"
    )
    print(
        f"Destination: {destination_root}"
    )
    print(
        f"Copied:      {copied} required files"
    )
    print(
        f"Generated:   {len(generated)} LaTeX tables + {len(figures)} PDF figure(s)"
    )
    print(
        f"Missing:     {len(missing)} required inputs/assets"
    )
    print(
        f"Size:        {human_size(source_size)} -> "
        f"{human_size(destination_size)}"
    )
    print()
    print(
        "Upload the generated 'thesis_results_latex' folder into the "
        "Overleaf 'figures/' directory."
    )

    if missing:
        print()
        print(
            "Outstanding Chapter-5 items:"
        )

        for path in missing:
            print(
                f"  - {path}"
            )

    if (
        args.strict
        and missing
    ):
        raise SystemExit(
            "Strict export failed because one or more required Chapter-5 "
            "assets or generated-table inputs are missing."
        )


if __name__ == "__main__":
    main()