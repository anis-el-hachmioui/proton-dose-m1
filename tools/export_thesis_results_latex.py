def _load_npz_arrays(path: Path, *names):
    """Load arrays from a results.npz, or None if the file or a key is absent."""

    import numpy as np

    if not path.is_file():
        return None

    with np.load(path) as data:
        if any(name not in data.files for name in names):
            return None
        return [np.asarray(data[name], dtype=float) for name in names]


def _idd_r80_dfw(z, dose, z_from=None):
    """R80 and DFW (R20 - R80) of the integrated depth dose, in metres.

    Same definition as ResultMetrics.range_metrics: the peak is the maximum
    of I(z) at depths z >= z_from.
    """

    import numpy as np

    idd = np.asarray(dose, dtype=float).sum(axis=(0, 1))
    i_start = 0 if z_from is None else int(np.searchsorted(z, z_from))
    i_peak = i_start + int(np.argmax(idd[i_start:]))

    def distal(level):
        target = level * float(idd[i_peak])
        for i in range(i_peak, len(idd) - 1):
            if idd[i] >= target > idd[i + 1]:
                return float(
                    z[i]
                    + (target - idd[i]) * (z[i + 1] - z[i])
                    / (idd[i + 1] - idd[i])
                )
        return None

    r80, r20 = distal(0.8), distal(0.2)
    return r80, (None if r80 is None or r20 is None else r20 - r80)


def _deepest_peak_depth(z, dose, window=10, min_fraction=0.3):
    """Depth of the deepest Bragg peak of I(z) (see distal_peak_index)."""

    import numpy as np

    idd = np.asarray(dose, dtype=float).sum(axis=(0, 1))
    threshold = min_fraction * float(np.max(idd))
    for i in range(len(idd) - 1, -1, -1):
        if idd[i] >= threshold and idd[i] >= float(
            np.max(idd[max(0, i - window):i + window + 1])
        ):
            return float(z[i])
    return float(z[int(np.argmax(idd))])


def generate_exact_reference_table(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """Reduced model against the exact analytical solution.

    For each reduced-model geometry: the BFP Monte Carlo reference and the
    WENO-Z solution, both compared with the exact CSDA free-streaming
    solution stored in the run (maximum-dose difference, Delta R80,
    Delta DFW, and for WENO-Z the 1%/1 mm gamma pass rate). The Monte Carlo
    row verifies the reference (also the heterogeneous transport path), the
    WENO-Z row gives the pure discretization error.
    """

    missing: list[Path] = []
    lines = [
        r"\begin{tabular}{l rr rrrr}",
        r"\toprule",
        (
            r" & \multicolumn{2}{c}{BFP Monte Carlo} & "
            r"\multicolumn{4}{c}{WENO-Z} \\"
        ),
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-7}",
        (
            r"Geometry & \shortstack{$\delta_{\max}$\\{}[\%]} & "
            r"\shortstack{$\Delta R_{80}$\\{}[mm]} & "
            r"\shortstack{$\delta_{\max}$\\{}[\%]} & "
            r"\shortstack{$\Delta R_{80}$\\{}[mm]} & "
            r"\shortstack{$\Delta\mathrm{DFW}$\\{}[mm]} & "
            r"\shortstack{$\gamma$ $1\%/1$\,mm\\{}[\%]} \\"
        ),
        r"\midrule",
    ]

    any_row = False
    for case, label in MODEL_TABLE_CASES:
        case_root = source_root / "reduced_physics" / case
        metrics_path = case_root / "comparison_metrics.json"
        npz_path = case_root / "weno_z" / "results.npz"

        arrays = _load_npz_arrays(
            npz_path, "z", "bfp_mc_dose", "analytical_dose"
        )
        if not metrics_path.is_file() or arrays is None:
            missing.append(Path("reduced_physics") / case / "weno_z")
            lines.append(rf"{label} & \multicolumn{{6}}{{l}}{{pending}} \\")
            continue

        z, mc, exact = arrays
        exact_block = _safe_metric(
            load_json(metrics_path), "weno_z", "exact_reference"
        )

        mc_delta = 100.0 * (mc.max() / exact.max() - 1.0)
        z_from = _deepest_peak_depth(z, exact) - 0.02
        mc_r80, _ = _idd_r80_dfw(z, mc, z_from)
        exact_r80, _ = _idd_r80_dfw(z, exact, z_from)
        mc_dr80 = (
            None
            if mc_r80 is None or exact_r80 is None
            else 1000.0 * (mc_r80 - exact_r80)
        )

        lines.append(
            " & ".join(
                [
                    label,
                    _latex_number(mc_delta, 2),
                    _latex_number(mc_dr80, 3),
                    _latex_number(
                        _safe_metric(
                            exact_block,
                            "maximum_dose",
                            "relative_difference_percent",
                        ),
                        2,
                    ),
                    _latex_number(
                        _safe_metric(
                            exact_block, "range", "r80_difference_mm"
                        ),
                        3,
                    ),
                    _latex_number(
                        _safe_metric(
                            exact_block, "range", "dfw_difference_mm"
                        ),
                        3,
                    ),
                    _latex_number(
                        _safe_metric(exact_block, "gamma", "1_percent_1_mm"),
                        2,
                        truncate=True,
                    ),
                ]
            )
            + r" \\"
        )
        any_row = True

    lines.extend([r"\bottomrule", r"\end{tabular}"])
    output = destination_root / "summary" / "reduced_exact_reference_table.tex"
    write_text(output, "\n".join(lines))
    return ([output] if any_row else [output]), missing


