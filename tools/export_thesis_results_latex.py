#!/usr/bin/env python3
"""Export only the thesis-result files that are consumed by Overleaf.

The full ``thesis_results`` tree contains raw solver output, cached run data,
NPZ arrays, JSON metadata, SVG/PNG previews, and individual diagnostic plots.
The thesis itself only needs a small subset of those files.

In addition to copying the figures/tables already generated by the experiment
pipeline, this exporter derives the Chapter-5 overview tables directly from
the machine-readable result JSON files:

- reference-verification summary table;
- Monte Carlo statistical-convergence table;
- full-physics benchmark summary table;
- one combined benchmark table per transport model (all geometries and
  reconstruction methods of that model in a single table);
- extended-model runtime-versus-accuracy PDF figure.

By default this script creates::

    thesis_results_latex/

next to ``thesis_results/`` at the repository root. The directory preserves
exactly the relative paths expected by Chapter 5, so it can be dragged into
``figures/`` in the Overleaf project.

Run from anywhere with::

    uv run tools/export_thesis_results_latex.py

Use ``--strict`` to fail if any required Chapter-5 asset is missing.
"""

