def generate_performance_table(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """Runtimes and the equal-accuracy speed-up for all benchmarks.

    Columns: deterministic runtime per scheme, WENO-Z runtime with the
    moving active domain, the BFP Monte Carlo runtime needed for a relative
    standard uncertainty of 1% in the peak region (from the batch estimate,
    tools/reference_uncertainty.py), and the speed-up of WENO-Z without and
    with the moving active domain relative to that equal-accuracy Monte
    Carlo runtime. A speed-up below one means that Monte Carlo is faster.
    """

    missing: list[Path] = []
    moving = _moving_domain_summary(source_root)

    lines = [
        r"\begin{tabular}{ll rrr r r rr}",
        r"\toprule",
        (
            r" & & \multicolumn{3}{c}{Deterministic [s]} & "
            r"\shortstack{WENO-Z\\moving} & "
            r"\shortstack{MC for\\$1\%$ [s]} & "
            r"\multicolumn{2}{c}{Speed-up WENO-Z} \\"
        ),
        r"\cmidrule(lr){3-5}\cmidrule(lr){8-9}",
        (
            r"Model & Geometry & First order & MUSCL & WENO-Z & "
            r"domain [s] & & static & moving \\"
        ),
        r"\midrule",
    ]

    for group_index, (group, _) in enumerate(MODEL_SUMMARY_TABLES):
        for case, label in MODEL_TABLE_CASES:
            metrics_path = source_root / group / case / "comparison_metrics.json"
            if not metrics_path.is_file():
                missing.append(metrics_path.relative_to(source_root))
                continue
            data = load_json(metrics_path)

            runtimes = [
                _safe_metric(
                    data.get(key, {}),
                    "performance",
                    "deterministic_runtime_seconds",
                )
                for key, _ in METHODS
            ]
            weno_runtime = runtimes[-1]

            moving_runtime = _safe_metric(
                moving.get(f"{group}/{case}/weno_z", {}),
                "deterministic_runtime_seconds",
            )

            uncertainty = _reference_uncertainty(source_root, group, case)
            mc_one_percent = _safe_metric(
                uncertainty or {},
                "target_uncertainty_peak_region",
                "1_percent",
                "runtime_seconds",
            )
            if uncertainty is None:
                missing.append(
                    Path("reference_uncertainty")
                    / f"{MODEL_KEYS[group]}__{case}.json"
                )

            def speedup(runtime):
                try:
                    return float(mc_one_percent) / float(runtime)
                except (TypeError, ValueError, ZeroDivisionError):
                    return None

            lines.append(
                " & ".join(
                    [
                        MODEL_LABELS[group],
                        label,
                        *[_latex_number(r, 0) for r in runtimes],
                        _latex_number(moving_runtime, 0),
                        _latex_number(mc_one_percent, 0),
                        _latex_number(speedup(weno_runtime), 2),
                        _latex_number(speedup(moving_runtime), 2),
                    ]
                )
                + r" \\"
            )
        if group_index == 0:
            lines.append(r"\addlinespace")

    lines.extend([r"\bottomrule", r"\end{tabular}"])
    output = destination_root / "summary" / "performance_table.tex"
    write_text(output, "\n".join(lines))
    return [output], list(dict.fromkeys(missing))


def generate_moving_domain_table(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """WENO-Z with and without the moving active domain (appendix).

    Runtime of both runs, the speed-up factor, and the largest dose
    difference between the two, relative to the maximum dose.
    """

    import numpy as np

    moving = _moving_domain_summary(source_root)
    missing: list[Path] = []
    if not moving:
        missing.append(Path("robustness/moving_active_domain/summary.json"))

    lines = [
        r"\begin{tabular}{ll rrrr}",
        r"\toprule",
        (
            r"Model & Geometry & \shortstack{Static\\{}[s]} & "
            r"\shortstack{Moving\\{}[s]} & Factor & "
            r"\shortstack{$\max|\Delta D|/\max D$} \\"
        ),
        r"\midrule",
    ]

    for group, _ in MODEL_SUMMARY_TABLES:
        for case, label in MODEL_TABLE_CASES:
            static_npz = source_root / group / case / "weno_z" / "results.npz"
            moving_npz = (
                source_root
                / "robustness"
                / "moving_active_domain"
                / group
                / case
                / "weno_z"
                / "results.npz"
            )
            metrics_path = source_root / group / case / "comparison_metrics.json"

            static_runtime = (
                _safe_metric(
                    load_json(metrics_path),
                    "weno_z",
                    "performance",
                    "deterministic_runtime_seconds",
                )
                if metrics_path.is_file()
                else None
            )
            moving_runtime = _safe_metric(
                moving.get(f"{group}/{case}/weno_z", {}),
                "deterministic_runtime_seconds",
            )

            a = _load_npz_arrays(static_npz, "dose")
            b = _load_npz_arrays(moving_npz, "dose")
            difference = (
                None
                if a is None or b is None
                else float(np.max(np.abs(b[0] - a[0])) / np.max(a[0]))
            )

            try:
                factor = float(static_runtime) / float(moving_runtime)
            except (TypeError, ValueError, ZeroDivisionError):
                factor = None

            lines.append(
                " & ".join(
                    [
                        MODEL_LABELS[group],
                        label,
                        _latex_number(static_runtime, 0),
                        _latex_number(moving_runtime, 0),
                        _latex_number(factor, 1),
                        (
                            "--"
                            if difference is None
                            else latex_scientific(difference)
                        ),
                    ]
                )
                + r" \\"
            )

    lines.extend([r"\bottomrule", r"\end{tabular}"])
    output = destination_root / "summary" / "moving_domain_table.tex"
    write_text(output, "\n".join(lines))
    return [output], missing


