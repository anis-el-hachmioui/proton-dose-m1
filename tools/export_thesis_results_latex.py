def generate_coarse_grid_table(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """WENO-Z errors on the benchmark grid and on the coarser grids.

    Reduced model: against the exact solution (no statistical noise).
    Extended model: against the BFP Monte Carlo reference of each grid.
    One row per grid, so the growth of the error with the cell size can be
    read down each benchmark.
    """

    missing: list[Path] = []
    lines = [
        r"\begin{tabular}{lll rrr}",
        r"\toprule",
        (
            r"Model & Geometry & Cells [mm] & $\delta_{\max}$ [\%] & "
            r"$\Delta R_{80}$ [mm] & $\Delta\mathrm{DFW}$ [mm] \\"
        ),
        r"\midrule",
    ]

    def values(metrics, exact):
        if metrics is None:
            return [None, None, None]
        block = (metrics.get("exact_reference") or {}) if exact else metrics
        return [
            _safe_metric(
                block, "maximum_dose", "relative_difference_percent"
            ),
            _safe_metric(block, "range", "r80_difference_mm"),
            _safe_metric(block, "range", "dfw_difference_mm"),
        ]

    first_block = True
    for group, _ in MODEL_SUMMARY_TABLES:
        exact = group == "reduced_physics"
        for case, label in MODEL_TABLE_CASES:
            if not first_block:
                lines.append(r"\addlinespace")
            first_block = False
            for row, (study, cells) in enumerate(COARSE_GRIDS):
                if study is None:
                    path = source_root / group / case / "comparison_metrics.json"
                    metrics = (
                        load_json(path).get("weno_z")
                        if path.is_file()
                        else None
                    )
                else:
                    path = (
                        source_root
                        / "robustness"
                        / study
                        / group
                        / case
                        / "weno_z"
                        / "metrics.json"
                    )
                    metrics = load_json(path) if path.is_file() else None
                if metrics is None:
                    missing.append(path.relative_to(source_root))

                v = values(metrics, exact)
                lines.append(
                    " & ".join(
                        [
                            MODEL_LABELS[group] if row == 0 else "",
                            label if row == 0 else "",
                            cells,
                            _latex_number(v[0], 2),
                            _latex_number(v[1], 3),
                            _latex_number(v[2], 3),
                        ]
                    )
                    + r" \\"
                )

    lines.extend([r"\bottomrule", r"\end{tabular}"])
    output = destination_root / "summary" / "coarse_grid_table.tex"
    write_text(output, "\n".join(lines))
    return [output], list(dict.fromkeys(missing))


def generate_scheme_order_table(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """Fitted L2 convergence orders of all three reconstructions."""

    missing: list[Path] = []
    studies = (
        ("reduced_physics_convergence", "Reduced"),
        ("scattering_nuclear_convergence", "Extended"),
    )
    schemes = (
        ("_first_order", "First order"),
        ("_muscl", "MUSCL"),
        ("", "WENO-Z"),
    )

    lines = [
        r"\begin{tabular}{ll rr}",
        r"\toprule",
        r"Model & Scheme & $p_{L^2}$ dose & $p_{L^2}$ $\Phi(60\,\mathrm{MeV})$ \\",
        r"\midrule",
    ]

    for study_index, (study, model_label) in enumerate(studies):
        for suffix, scheme_label in schemes:
            path = (
                source_root
                / "numerical_verification"
                / f"{study}{suffix}"
                / "convergence_summary.json"
            )
            orders = [None, None]
            if path.is_file():
                observables = load_json(path).get("observables", {})
                for key, data in observables.items():
                    order = _safe_metric(data, "l2", "fitted_order")
                    if key.startswith("dose"):
                        orders[0] = order
                    elif key.startswith("phi"):
                        orders[1] = order
            else:
                missing.append(path.relative_to(source_root))

            lines.append(
                " & ".join(
                    [
                        model_label,
                        scheme_label,
                        _latex_number(orders[0], 2),
                        _latex_number(orders[1], 2),
                    ]
                )
                + r" \\"
            )
        if study_index == 0:
            lines.append(r"\addlinespace")

    lines.extend([r"\bottomrule", r"\end{tabular}"])
    output = destination_root / "summary" / "scheme_order_table.tex"
    write_text(output, "\n".join(lines))
    return [output], list(dict.fromkeys(missing))


