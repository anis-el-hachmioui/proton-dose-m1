def human_size(num_bytes: int) -> str:
    value = float(num_bytes)

    for unit in ("B", "KiB", "MiB", "GiB"):
        if value < 1024.0 or unit == "GiB":
            return f"{value:.1f} {unit}"

        value /= 1024.0

    raise AssertionError("unreachable")


def directory_size(path: Path) -> int:
    if not path.exists():
        return 0

    return sum(
        file.stat().st_size
        for file in path.rglob("*")
        if file.is_file()
    )


def copy_asset(
    source_root: Path,
    destination_root: Path,
    relative_path: Path,
) -> bool:
    source = source_root / relative_path

    if not source.is_file():
        print(f"[missing] {relative_path}")
        return False

    destination = destination_root / relative_path

    destination.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    shutil.copy2(
        source,
        destination,
    )

    print(f"[copy]    {relative_path}")

    return True


def load_json(path: Path):
    with path.open(
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


def write_text(
    path: Path,
    contents: str,
) -> None:
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    path.write_text(
        contents.rstrip() + "\n",
        encoding="utf-8",
    )

    print(
        f"[generate] {path}"
    )


def latex_scientific(
    value: float,
    *,
    significant_digits: int = 3,
) -> str:
    """Format a positive/negative float compactly for a LaTeX table."""

    value = float(value)

    if value == 0.0:
        return "$0$"

    exponent = int(
        math.floor(
            math.log10(abs(value))
        )
    )

    mantissa = (
        value
        / (10.0 ** exponent)
    )

    decimals = max(
        0,
        significant_digits - 1,
    )

    return (
        f"${mantissa:.{decimals}f}"
        rf"\times 10^{{{exponent}}}$"
    )


def latex_histories(histories: int) -> str:
    """Format an MC history count as a power of ten for LaTeX."""

    histories = int(histories)
    exponent = len(str(histories)) - 1
    mantissa, remainder = divmod(histories, 10**exponent)

    if remainder != 0:
        return f"{histories:,}"

    if mantissa == 1:
        return rf"$10^{{{exponent}}}$"

    return rf"${mantissa}\times10^{{{exponent}}}$"


def generate_reference_tables(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """Generate the two BFP-reference tables used by Chapter 5."""

    relative_json = Path(
        "reference_verification/"
        "bfp_mc_vs_analytical/"
        "reference_convergence.json"
    )

    source_json = (
        source_root
        / relative_json
    )

    if not source_json.is_file():
        print(
            f"[missing] {relative_json}"
        )
        return [], [relative_json]

    records = load_json(
        source_json
    )

    if not records:
        print(
            f"[missing] empty {relative_json}"
        )
        return [], [relative_json]

    records = sorted(
        records,
        key=lambda row: int(
            row["histories"]
        ),
    )

    final = records[-1]

    reference_root = (
        destination_root
        / "reference_verification"
        / "bfp_mc_vs_analytical"
    )

    verification_path = (
        reference_root
        / "verification_table.tex"
    )

    # Relative L2 error of the laterally integrated depth dose, recorded by
    # the reference verification since the converged analytical quadrature.
    idd_row = (
        "Relative $L^2$ error of integrated depth dose & "
        + latex_scientific(final["idd_l2"])
        + " \\\\\n"
        if "idd_l2" in final
        else ""
    )

    verification_table = rf"""
\begin{{tabular}}{{lc}}
\toprule
Metric & Value \\
\midrule
BFP histories & {latex_histories(final["histories"])} \\
Relative $L^1$ dose error & {latex_scientific(final["l1"])} \\
Relative $L^2$ dose error & {latex_scientific(final["l2"])} \\
Relative $L^\infty$ dose error & {latex_scientific(final["linf"])} \\
{idd_row}Bragg-peak depth difference [mm] & {float(final["peak_depth_difference_mm"]):.3f} \\
BFP MC runtime [s] & {float(final["runtime_seconds"]):.3f} \\
\bottomrule
\end{{tabular}}
"""

    write_text(
        verification_path,
        verification_table,
    )

    convergence_path = (
        reference_root
        / "statistical_convergence_table.tex"
    )

    rows = []

    for row in records:
        rows.append(
            "{} & {} & {:.3f} \\\\".format(
                latex_histories(
                    row["histories"]
                ),
                latex_scientific(
                    row["l2"]
                ),
                float(
                    row["runtime_seconds"]
                ),
            )
        )

    convergence_table = "\n".join(
        [
            r"\begin{tabular}{rcc}",
            r"\toprule",
            r"Histories & Relative $L^2$ dose error & Runtime [s] \\",
            r"\midrule",
            *rows,
            r"\bottomrule",
            r"\end{tabular}",
        ]
    )

    write_text(
        convergence_path,
        convergence_table,
    )

    return (
        [
            verification_path,
            convergence_path,
        ],
        [],
    )


def _safe_metric(
    data: dict,
    *keys,
):
    value = data

    for key in keys:
        if not isinstance(
            value,
            dict,
        ):
            return None

        value = value.get(
            key
        )

        if value is None:
            return None

    return value


def generate_full_physics_summary(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """Generate the final full-physics accuracy/runtime summary table."""

    lines = [
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        (
            r"Geometry & Scheme & "
            r"$\gamma_{1\%/1\mathrm{mm}}$ [\%] & "
            r"Max. dose diff. [\%] & Runtime [s] & "
            r"Speedup vs. BFP \\"
        ),
        r"\midrule",
    ]

    missing_inputs: list[Path] = []

    for case_index, (
        case,
        geometry_label,
    ) in enumerate(
        FULL_PHYSICS_CASES
    ):
        relative_json = (
            Path(
                "scattering_nuclear"
            )
            / case
            / "comparison_metrics.json"
        )

        source_json = (
            source_root
            / relative_json
        )

        if source_json.is_file():
            data = load_json(
                source_json
            )

            first_row = True

            for method_key, method_label in METHODS:
                metrics = data.get(
                    method_key
                )

                if metrics is None:
                    continue

                gamma = _safe_metric(
                    metrics,
                    "gamma",
                    "1_percent_1_mm",
                    "pass_rate_percent",
                )

                dose_difference = _safe_metric(
                    metrics,
                    "maximum_dose",
                    "relative_difference_percent",
                )

                runtime = _safe_metric(
                    metrics,
                    "performance",
                    "deterministic_runtime_seconds",
                )

                speedup = _safe_metric(
                    metrics,
                    "performance",
                    "speedup_vs_bfp_mc_x",
                )

                geometry_cell = (
                    geometry_label
                    if first_row
                    else ""
                )

                first_row = False

                def fmt(value):
                    if value is None:
                        return "--"
                    return f"{float(value):.3f}"

                lines.append(
                    "{} & {} & {} & {} & {} & {} \\\\".format(
                        geometry_cell,
                        method_label,
                        fmt(gamma),
                        fmt(dose_difference),
                        fmt(runtime),
                        fmt(speedup),
                    )
                )

        else:
            # Make missing benchmark inputs visible rather than silently
            # pretending they contain measurements.
            lines.append(
                rf"{geometry_label} & "
                r"\multicolumn{5}{c}{Pending benchmark} \\"
            )

            missing_inputs.append(
                relative_json
            )

        if (
            case_index
            != len(
                FULL_PHYSICS_CASES
            )
            - 1
        ):
            lines.append(
                r"\addlinespace"
            )

    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}",
        ]
    )

    summary_path = (
        destination_root
        / "summary"
        / "full_physics_summary_table.tex"
    )

    write_text(
        summary_path,
        "\n".join(lines),
    )

    return (
        [summary_path],
        missing_inputs,
    )


def _latex_number(
    value,
    decimals: int,
    *,
    truncate: bool = False,
) -> str:
    """Format a number in math mode, so that negative values get a minus sign.

    With ``truncate=True`` the value is rounded down instead of to nearest.
    This is used for pass rates, so that 100.00 is printed only when every
    evaluated voxel passes.
    """

    if value is None:
        return "--"

    try:
        value = float(value)
    except (TypeError, ValueError):
        return "--"

    if not math.isfinite(value):
        return "--"

    if truncate:
        scale = 10.0 ** decimals
        value = math.floor(value * scale + 1e-9) / scale

    text = f"{value:.{decimals}f}"
    if float(text) == 0.0:
        text = text.lstrip("-")  # no "-0.000" for values that round to zero
    return f"${text}$"


def generate_model_benchmark_tables(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """Generate one combined accuracy table per transport model.

    Each table lists, for every geometry and reconstruction method of one
    model, the three gamma pass rates, the maximum-dose difference and the
    differences in the distal range R80 and the distal falloff width
    DFW = R20 - R80 of the integrated depth dose, all relative to the BFP
    Monte Carlo reference. Runtimes are in the separate performance table.
    """

    generated: list[Path] = []
    missing_inputs: list[Path] = []

    header = [
        r"\begin{tabular}{l rrr rrr}",
        r"\toprule",
        (
            r" & \multicolumn{3}{c}{$\gamma$ pass rate [\%]} & "
            r"\multicolumn{3}{c}{Difference to reference} \\"
        ),
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
        (
            r"Scheme & $3\%/3$\,mm & $2\%/2$\,mm & $1\%/1$\,mm & "
            r"\shortstack{$\delta_{\max}$\\{}[\%]} & "
            r"\shortstack{$\Delta R_{80}$\\{}[mm]} & "
            r"\shortstack{$\Delta\mathrm{DFW}$\\{}[mm]} \\"
        ),
        r"\midrule",
    ]

    for group, filename in MODEL_SUMMARY_TABLES:
        lines = list(header)

        for case_index, (case, geometry_label) in enumerate(
            MODEL_TABLE_CASES
        ):
            relative_json = Path(group) / case / "comparison_metrics.json"
            source_json = source_root / relative_json

            if not source_json.is_file():
                print(f"[missing] {relative_json}")
                missing_inputs.append(relative_json)
                lines.append(
                    rf"\multicolumn{{7}}{{l}}{{\emph{{{geometry_label}}}: "
                    r"pending benchmark} \\"
                )
            else:
                data = load_json(source_json)
                lines.append(
                    rf"\multicolumn{{7}}{{l}}{{\emph{{{geometry_label}}}}} \\"
                )

                for method_key, method_label in METHODS:
                    metrics = data.get(method_key)

                    if metrics is None:
                        continue

                    gammas = [
                        _latex_number(
                            _safe_metric(
                                metrics,
                                "gamma",
                                criterion,
                                "pass_rate_percent",
                            ),
                            2,
                            truncate=True,
                        )
                        for criterion in (
                            "3_percent_3_mm",
                            "2_percent_2_mm",
                            "1_percent_1_mm",
                        )
                    ]

                    lines.append(
                        " & ".join(
                            [
                                r"\quad " + method_label,
                                *gammas,
                                _latex_number(
                                    _safe_metric(
                                        metrics,
                                        "maximum_dose",
                                        "relative_difference_percent",
                                    ),
                                    1,
                                ),
                                _latex_number(
                                    _safe_metric(
                                        metrics, "range", "r80_difference_mm"
                                    ),
                                    2,
                                ),
                                _latex_number(
                                    _safe_metric(
                                        metrics, "range", "dfw_difference_mm"
                                    ),
                                    2,
                                ),
                            ]
                        )
                        + r" \\"
                    )

            if case_index != len(MODEL_TABLE_CASES) - 1:
                lines.append(r"\addlinespace")

        lines.extend([r"\bottomrule", r"\end{tabular}"])

        output = destination_root / "summary" / filename
        write_text(output, "\n".join(lines))
        generated.append(output)

    return (
        generated,
        list(dict.fromkeys(missing_inputs)),
    )


