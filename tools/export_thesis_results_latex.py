def generate_runtime_accuracy_tradeoff(
    source_root: Path,
    destination_root: Path,
) -> tuple[list[Path], list[Path]]:
    """Plot the extended-model accuracy/runtime trade-off from benchmark JSON.

    Uses exactly the same inputs and metrics as the extended-model summary
    table. All nine points (three geometries x three methods) are required;
    an incomplete or invalid dataset will not produce a misleading plot.
    """

    import matplotlib

    matplotlib.use("Agg")  # Headless PDF generation, including over SSH.
    import matplotlib.pyplot as plt

    geometry_labels = {
        "homogeneous_water": "H",
        "longitudinal_slabs": "D",
        "transversal_slabs": "L",
    }
    method_markers = {
        "first_order": "o",
        "muscl": "s",
        "weno_z": "^",
    }
    measurements: dict[str, list[tuple[float, float, str]]] = {
        method: [] for method, _ in METHODS
    }
    missing: list[Path] = []

    for case, _ in FULL_PHYSICS_CASES:
        relative_json = (
            Path("scattering_nuclear") / case / "comparison_metrics.json"
        )
        json_path = source_root / relative_json
        if not json_path.is_file():
            print(f"[missing] {relative_json}")
            missing.append(relative_json)
            continue

        data = load_json(json_path)
        for method, _ in METHODS:
            metrics = data.get(method)
            runtime = _safe_metric(
                metrics, "performance", "deterministic_runtime_seconds"
            )
            gamma = _safe_metric(
                metrics, "gamma", "1_percent_1_mm", "pass_rate_percent"
            )
            try:
                x, y = float(runtime), float(gamma)
                valid = (
                    math.isfinite(x) and x > 0
                    and math.isfinite(y) and 0 <= y <= 100
                )
            except (TypeError, ValueError):
                valid = False

            if not valid:
                print(f"[missing] {relative_json}: {method} runtime/gamma")
                missing.append(relative_json)
                continue

            measurements[method].append((x, y, geometry_labels[case]))

    if missing:
        print("[skip]    runtime_accuracy_tradeoff.pdf: incomplete benchmark data")
        return [], list(dict.fromkeys(missing))

    fig, ax = plt.subplots(figsize=(7.3, 4.6))
    for method, label in METHODS:
        points = measurements[method]
        ax.scatter(
            [x for x, _, _ in points],
            [y for _, y, _ in points],
            marker=method_markers[method],
            s=75,
            label=label,
            zorder=3,
        )
        for runtime, gamma, geom_label in points:
            ax.annotate(
                geom_label,
                (runtime, gamma),
                xytext=(6, 5),
                textcoords="offset points",
                fontsize=9,
            )

    ax.set_xscale("log")
    ax.set_xlabel("Deterministic runtime [s]")
    ax.set_ylabel("Gamma pass rate (1% / 1 mm) [%]")
    y_min = min(y for rows in measurements.values() for _, y, _ in rows)
    ax.set_ylim(max(0, 5 * math.floor((y_min - 5) / 5)), 103)
    ax.grid(alpha=0.2, which="both")
    ax.legend(
        frameon=False,
        ncol=3,
        loc="lower center",
        bbox_to_anchor=(0.5, 1.015),
    )
    fig.tight_layout()

    output = destination_root / "summary" / "runtime_accuracy_tradeoff.pdf"
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, bbox_inches="tight")
    plt.close(fig)
    print(f"[generate] {output}")
    return [output], []


